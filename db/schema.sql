CREATE TABLE IF NOT EXISTS admin_users (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS content_items (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 type ENUM('coupon','news','ad') NOT NULL,
 title VARCHAR(160) NOT NULL,
 summary TEXT NOT NULL,
 brand VARCHAR(100) NOT NULL DEFAULT '',
 category VARCHAR(80) NOT NULL DEFAULT 'General',
 code VARCHAR(80) NOT NULL DEFAULT '',
 url VARCHAR(1024) NOT NULL,
 placement ENUM('home','offers','news') NOT NULL DEFAULT 'offers',
 priority SMALLINT NOT NULL DEFAULT 0,
 status ENUM('draft','published') NOT NULL DEFAULT 'draft',
 starts_at DATETIME NULL,
 expires_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY status_type (status,type),
 KEY active_dates (starts_at,expires_at),
 KEY placement_priority (placement,priority)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS campaign_stats (
 campaign_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 clicks BIGINT UNSIGNED NOT NULL DEFAULT 0,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_campaign FOREIGN KEY (campaign_id) REFERENCES content_items(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
